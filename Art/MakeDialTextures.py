"""Original readable instrument artwork; no external image assets or fonts bundled."""
from PIL import Image,ImageDraw,ImageFont
from pathlib import Path
import math,json
import array
ROOT=Path(__file__).resolve().parents[1]; OUT=ROOT/'Art/Textures/Original'; OUT.mkdir(parents=True,exist_ok=True)
font_path=next(str(p) for p in [Path('C:/Windows/Fonts/arial.ttf'),Path('/System/Library/Fonts/Supplemental/Arial.ttf'),Path('/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf')] if p.exists())
def font(size): return ImageFont.truetype(font_path,size)
names=['AIRSPEED','ATTITUDE','ALTITUDE','HEADING','VERT SPEED','RPM x100']
labels=[['0','20','40','60','80','100','120','140','160','180'],[],[str(j) for j in range(10)],['N','3','6','E','12','15','S','21','24','W','30','33'],['-20','-10','0','10','20'],['0','5','10','15','20','25','30']]
atlas=Image.new('RGB',(2048,1024),(12,17,16))
for index,name in enumerate(names):
    im=Image.new('RGB',(512,512),(13,19,18)); d=ImageDraw.Draw(im)
    for radius,col in [(249,(55,63,61)),(239,(110,116,108)),(235,(14,20,19)),(220,(27,34,31))]: d.ellipse((256-radius,256-radius,256+radius,256+radius),fill=col)
    start=-130 if index in (0,5) else 0 if index in (2,3) else -130
    span=260 if index in (0,4,5) else 360
    tick_count=50 if index==2 else 60 if index==3 else 45
    if index!=1:
        for j in range(tick_count+1):
            a=math.radians(start+span*j/tick_count)
            rr=185 if j%5 else 174; c=(188,198,184)
            d.line((256+math.sin(a)*rr,256-math.cos(a)*rr,256+math.sin(a)*203,256-math.cos(a)*203),fill=c,width=3 if j%5 else 5)
        for j,label in enumerate(labels[index]):
            fraction=j/(len(labels[index]) if index in (2,3) else len(labels[index])-1)
            a=math.radians(start+span*fraction)
            d.text((256+math.sin(a)*148,256-math.cos(a)*148),label,font=font(26),fill=(221,225,206),anchor='mm')
    else:
        for a in (-60,-30,0,30,60):
            a=math.radians(a); d.line((256+math.sin(a)*184,256-math.cos(a)*184,256+math.sin(a)*206,256-math.cos(a)*206),fill=(220,227,211),width=4)
    d.text((256,305),name,font=font(22),fill=(198,205,183),anchor='mm')
    unit=['KNOTS','','FEET','MAGNETIC','FT/M x100','DERIVED'][index]
    d.text((256,336),unit,font=font(17),fill=(133,151,137),anchor='mm')
    if index==0:
        for a in range(-65,75):
            r=math.radians(a); d.ellipse((254+math.sin(r)*216,254-math.cos(r)*216,258+math.sin(r)*216,258-math.cos(r)*216),fill=(88,155,87))
    x0=round((index%3)*2048/3); x1=round((index%3+1)*2048/3)
    atlas.paste(im.resize((x1-x0,512),Image.Resampling.LANCZOS),(x0,(index//3)*512))
atlas.save(OUT/'instrument_atlas.png')
height_path=ROOT/'Art/Exports/coast.r16'
if height_path.exists():
    heights=array.array('H'); heights.frombytes(height_path.read_bytes())
    mask=bytearray()
    for v in heights:
        h=(v-32768)/50
        foam=math.exp(-abs(h+.55)/1.3)*max(0,min(1,-h/.25))
        mask.extend((round(foam*255),round(max(0,min(1,-h/30))*255),0))
    Image.frombytes('RGB',(1009,1009),bytes(mask)).resize((1024,1024),Image.Resampling.BILINEAR).save(OUT/'shore_mask.png')
(OUT/'README.md').write_text('Original Aeronaut instrument artwork generated by MakeDialTextures.py. The system Arial font is rasterized into markings; the font file is not distributed. AircraftSurfaceNormal is baked from our Blender materials.\n')
